export function getFontPresetById(id: string): FontPreset {
  return FONT_PRESETS.find((f) => f.id === id) || FONT_PRESETS[0]
}

export function getFontVariables(presetId: string): Record<string, string> {
  const preset = getFontPresetById(presetId)

  return {
    '--font-script': `'${preset.script}', ${preset.scriptFallback}`,
    '--font-display': `'${preset.display}', ${preset.displayFallback}`,
    '--font-elegant': `'${preset.elegant}', ${preset.elegantFallback}`,
    '--font-body': `'${preset.body}', ${preset.bodyFallback}`,
  }
}

// Load fonts untuk preset tertentu
export function getGoogleFontsUrl(presetIds: string[] = []): string {
  const presets = presetIds.length > 0
    ? FONT_PRESETS.filter((p) => presetIds.includes(p.id))
    : FONT_PRESETS

  const fontFamilies = new Set<string>()

  presets.forEach((preset) => {
    fontFamilies.add(`${preset.script.replace(/ /g, '+')}:wght@400`)
    fontFamilies.add(`${preset.display.replace(/ /g, '+')}:wght@400;500;600;700`)
    fontFamilies.add(`${preset.elegant.replace(/ /g, '+')}:ital,wght@0,400;0,500;1,400`)
    fontFamilies.add(`${preset.body.replace(/ /g, '+')}:wght@300;400;500;600`)
  })

  return `https://fonts.googleapis.com/css2?${Array.from(fontFamilies)
    .map((f) => `family=${f}`)
    .join('&')}&display=swap`
}
